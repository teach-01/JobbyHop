/**
 * Non-destructive migration script for JobbyHop uploads to Cloudinary.
 *
 * Scans `backend/uploads/`, uploads real images to Cloudinary (folder: `jobbyhop/legacy-uploads`),
 * and updates any matching database records (`WorkerProfile`, `RecruiterProfile`, `AuditLog`).
 *
 * CRITICAL SAFETY RULES:
 * 1. Default mode is DRY-RUN (`--dry-run`). No changes are made to Cloudinary or DB without `--execute`.
 * 2. NEVER DELETES OR MODIFIES ANY LOCAL FILE in `backend/uploads/`.
 * 3. Does not run against production unless explicitly invoked with environment variables and `--execute`.
 *
 * Usage:
 *   # Inspect what will be migrated without making changes:
 *   node src/utils/migrateUploadsToCloudinary.js --dry-run
 *
 *   # Execute migration after setting Cloudinary credentials and reviewing dry-run:
 *   node src/utils/migrateUploadsToCloudinary.js --execute
 */

const fs = require('fs');
const path = require('path');
const mongoose = require('mongoose');
require('dotenv').config({ path: path.join(__dirname, '../../.env') });

const {
  UPLOADS_DIR,
  isCloudinaryConfigured,
  getCloudinary,
} = require('./imageStorage');
const { detectImageMimeFromBuffer } = require('./imageValidator');
const { connectWithDnsFallback } = require('../config/db');

// Helper to check CLI flags
const args = process.argv.slice(2);
const isExecute = args.includes('--execute');
const isDryRun = !isExecute || args.includes('--dry-run');

async function runMigration() {
  console.log('====================================================');
  console.log(' JobbyHop — Cloudinary Image Migration Utility');
  console.log('====================================================');
  console.log(`Mode: ${isExecute ? '🚀 EXECUTE (LIVE)' : '🔍 DRY RUN (NO CHANGES)'}`);
  console.log(`Local uploads directory: ${UPLOADS_DIR}`);

  // 1. Check directory
  if (!fs.existsSync(UPLOADS_DIR)) {
    console.error(`Uploads directory not found: ${UPLOADS_DIR}`);
    process.exit(1);
  }

  // 2. Check Cloudinary credentials
  const cldConfigured = isCloudinaryConfigured();
  if (!cldConfigured) {
    console.warn('\n⚠️  Cloudinary credentials are not configured in backend environment!');
    console.warn('Required variables:');
    console.warn('  CLOUDINARY_CLOUD_NAME');
    console.warn('  CLOUDINARY_API_KEY');
    console.warn('  CLOUDINARY_API_SECRET');
    console.warn('  or CLOUDINARY_URL\n');
    if (isExecute) {
      console.error('Cannot run in --execute mode without Cloudinary credentials configured.');
      process.exit(1);
    }
    console.log('Continuing dry-run in inspection-only mode...\n');
  } else {
    console.log('✅ Cloudinary credentials detected.');
  }

  // 3. Scan local files
  const files = await fs.promises.readdir(UPLOADS_DIR);
  console.log(`Found ${files.length} files in local uploads folder.`);

  let realImagesCount = 0;
  let testStubCount = 0;
  const filesToMigrate = [];

  for (const filename of files) {
    const filePath = path.join(UPLOADS_DIR, filename);
    const stat = await fs.promises.stat(filePath);

    if (!stat.isFile()) continue;

    // Fast check: files < 100 bytes are typically test stubs (1x1 PNGs generated by unit tests)
    if (stat.size < 100) {
      testStubCount++;
      continue;
    }

    try {
      const buffer = await fs.promises.readFile(filePath);
      const mime = detectImageMimeFromBuffer(buffer);
      if (mime) {
        realImagesCount++;
        filesToMigrate.push({
          filename,
          filePath,
          size: stat.size,
          mime,
          localUrl: `/uploads/${filename}`,
        });
      } else {
        testStubCount++;
      }
    } catch {
      // Ignored
    }
  }

  console.log(`  - Real image candidates on disk: ${realImagesCount}`);
  console.log(`  - Test stubs / non-images skipped: ${testStubCount}`);

  // 4. Connect to MongoDB to audit references
  let dbConnected = false;
  let WorkerProfile = null;
  let RecruiterProfile = null;
  let AuditLog = null;

  if (process.env.MONGODB_URI) {
    try {
      console.log('\nConnecting to MongoDB to check references...');
      await connectWithDnsFallback(process.env.MONGODB_URI, {
        serverSelectionTimeoutMS: 5000,
      });
      dbConnected = true;
      console.log(`Connected to MongoDB host: ${mongoose.connection.host}`);

      // Load models
      WorkerProfile = require('../models/WorkerProfile');
      RecruiterProfile = require('../models/RecruiterProfile');
      AuditLog = require('../models/AuditLog');
    } catch (dbErr) {
      console.warn(`Could not connect to MongoDB (${dbErr.message}). Skipping database inspection.`);
    }
  } else {
    console.log('\nMONGODB_URI not set. Skipping database lookup.');
  }

  let dbMatches = 0;
  let dbUpdated = 0;
  let uploadedCount = 0;

  // 5. Bidirectional Audit: Check DB records for /uploads/ references
  if (dbConnected) {
    console.log('\n--- Auditing Database Records for Photo References ---');
    const dbWorkers = await WorkerProfile.find({ profilePhoto: { $regex: /^\/?uploads\//i } }, 'fullName profilePhoto');
    const dbRecruiters = await RecruiterProfile.find({ companyLogo: { $regex: /^\/?uploads\//i } }, 'companyName companyLogo');
    const dbAuditLogs = await AuditLog.find({
      $or: [
        { 'previousValue.profileImage': { $regex: /^\/?uploads\//i } },
        { 'previousValue.profileInformation.profilePhoto': { $regex: /^\/?uploads\//i } },
        { 'previousValue.profileInformation.companyLogo': { $regex: /^\/?uploads\//i } },
        { 'entityData.workerProfile.profilePhoto': { $regex: /^\/?uploads\//i } },
        { 'entityData.recruiterProfile.companyLogo': { $regex: /^\/?uploads\//i } },
      ],
    }).limit(20);

    console.log(`Workers with /uploads/ photos in DB:     ${dbWorkers.length}`);
    console.log(`Recruiters with /uploads/ logos in DB:    ${dbRecruiters.length}`);
    console.log(`Audit Logs with /uploads/ images in DB:   ${dbAuditLogs.length}`);

    // Check each DB reference against local disk
    for (const w of dbWorkers) {
      const fn = (w.profilePhoto || '').replace(/^\/?uploads\//, '');
      const fullPath = path.join(UPLOADS_DIR, fn);
      const existsOnDisk = fs.existsSync(fullPath);
      if (existsOnDisk) {
        console.log(`  [MATCH] Worker "${w.fullName}" (${w._id}): ${fn} exists on disk.`);
      } else {
        console.warn(`  [MISSING ON DISK] Worker "${w.fullName}" (${w._id}): references ${w.profilePhoto}, but file does not exist in local uploads folder.`);
      }
    }

    for (const r of dbRecruiters) {
      const fn = (r.companyLogo || '').replace(/^\/?uploads\//, '');
      const fullPath = path.join(UPLOADS_DIR, fn);
      const existsOnDisk = fs.existsSync(fullPath);
      if (existsOnDisk) {
        console.log(`  [MATCH] Recruiter "${r.companyName}" (${r._id}): ${fn} exists on disk.`);
      } else {
        console.warn(`  [MISSING ON DISK] Recruiter "${r.companyName}" (${r._id}): references ${r.companyLogo}, but file does not exist in local uploads folder.`);
      }
    }
    console.log('------------------------------------------------------\n');
  }

  // 6. Inspect local files and match to DB records
  for (const item of filesToMigrate) {
    let workerCount = 0;
    let recruiterCount = 0;
    let auditCount = 0;

    if (dbConnected) {
      workerCount = await WorkerProfile.countDocuments({ profilePhoto: item.localUrl });
      recruiterCount = await RecruiterProfile.countDocuments({ companyLogo: item.localUrl });
      auditCount = await AuditLog.countDocuments({
        $or: [
          { 'previousValue.profileImage': item.localUrl },
          { 'previousValue.profileInformation.profilePhoto': item.localUrl },
          { 'previousValue.profileInformation.companyLogo': item.localUrl },
          { 'entityData.workerProfile.profilePhoto': item.localUrl },
          { 'entityData.recruiterProfile.companyLogo': item.localUrl },
        ],
      });
    }

    const totalRefs = workerCount + recruiterCount + auditCount;
    if (totalRefs > 0) {
      dbMatches++;
    }

    if (isDryRun) {
      if (totalRefs > 0) {
        console.log(`[DRY-RUN] Linked File: ${item.filename} (${item.size} bytes) -> DB refs: Workers: ${workerCount}, Recruiters: ${recruiterCount}, Audits: ${auditCount}`);
      }
    } else if (isExecute && cldConfigured) {
      try {
        const cld = getCloudinary();
        console.log(`Uploading ${item.filename} (${item.size} bytes)...`);
        const uploadRes = await cld.uploader.upload(item.filePath, {
          folder: 'jobbyhop/legacy-uploads',
          resource_type: 'image',
        });

        uploadedCount++;
        const newUrl = uploadRes.secure_url;
        console.log(`  -> Uploaded to ${newUrl}`);

        if (dbConnected && totalRefs > 0) {
          if (workerCount > 0) {
            await WorkerProfile.updateMany({ profilePhoto: item.localUrl }, { $set: { profilePhoto: newUrl } });
          }
          if (recruiterCount > 0) {
            await RecruiterProfile.updateMany({ companyLogo: item.localUrl }, { $set: { companyLogo: newUrl } });
          }
          if (auditCount > 0) {
            await AuditLog.updateMany(
              { 'previousValue.profileImage': item.localUrl },
              { $set: { 'previousValue.profileImage': newUrl } }
            );
            await AuditLog.updateMany(
              { 'entityData.workerProfile.profilePhoto': item.localUrl },
              { $set: { 'entityData.workerProfile.profilePhoto': newUrl } }
            );
            await AuditLog.updateMany(
              { 'entityData.recruiterProfile.companyLogo': item.localUrl },
              { $set: { 'entityData.recruiterProfile.companyLogo': newUrl } }
            );
          }
          dbUpdated += totalRefs;
          console.log(`  -> Updated ${totalRefs} DB records to new URL.`);
        }
      } catch (uploadErr) {
        console.error(`  ❌ Failed to upload ${item.filename}:`, uploadErr.message);
      }
    }
  }

  if (dbConnected) {
    await mongoose.disconnect();
  }

  console.log('\n====================================================');
  console.log(' Migration Summary');
  console.log('====================================================');
  console.log(`Total local files scanned:     ${files.length}`);
  console.log(`Valid images identified:       ${realImagesCount}`);
  console.log(`Local files linked to DB:      ${dbMatches}`);
  if (isExecute) {
    console.log(`Images uploaded to Cloud:      ${uploadedCount}`);
    console.log(`DB records updated:            ${dbUpdated}`);
  } else {
    console.log(`Mode:                          DRY RUN (no files modified, no records updated)`);
    console.log('\nTo execute after verifying Cloudinary credentials:');
    console.log('  node src/utils/migrateUploadsToCloudinary.js --execute');
  }
  console.log('Local files retained:          100% (0 files deleted)');
  console.log('====================================================\n');
}

if (require.main === module) {
  runMigration().catch((err) => {
    console.error('Fatal error during migration:', err);
    process.exit(1);
  });
}

module.exports = { runMigration };
